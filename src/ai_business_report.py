def resolve_visualization_filename(
    visualization: dict,
    index: int
) -> str:

    filename = visualization.get(
        "filename"
    )

    if filename:
        return filename

    filename = visualization.get(
        "output_file"
    )

    if filename:
        return filename

    title = visualization.get(
        "title",
        f"Visualization {index}"
    )

    safe_title = re.sub(
        r"[^a-z0-9]+",
        "_",
        title.lower()
    ).strip("_")

    return (
        f"{index:02d}_"
        f"{safe_title}.png"
    )


