# REPORTLAB HELPERS
# ============================================================

def markdown_inline_to_reportlab(text: str) -> str:
    """
    Convert a subset of Markdown inline formatting
    into ReportLab-compatible XML.

    The converter is intentionally defensive because AI-generated
    Markdown may contain malformed or overlapping * / ** markers.
    """

    text = text.strip()

    # ------------------------------------------------------------
    # 1. Escape XML first
    # ------------------------------------------------------------
    text = html.escape(text, quote=False)

    # ------------------------------------------------------------
    # 2. Inline code
    # ------------------------------------------------------------
    # Convert inline code before bold/italic processing so that
    # Markdown-like characters inside code are not interpreted.
    placeholders = {}

    def store_placeholder(match):
        key = f"@@INLINE_CODE_{len(placeholders)}@@"
        placeholders[key] = (
            "<font name='Courier'>"
            + match.group(1)
            + "</font>"
        )
        return key

    text = re.sub(
        r"`([^`]+)`",
        store_placeholder,
        text
    )

    # ------------------------------------------------------------
    # 3. Normalize common malformed AI Markdown
    # ------------------------------------------------------------
    # Example:
    # **DAILY*REVENUE**
    #
    # This can otherwise produce:
    # <b>DAILY<i>REVENUE</b>
    #
    # Remove the overlapping single * inside a **...** expression.
    text = re.sub(
        r"\*\*([^*\n]+)\*([^*\n]+)\*\*",
        r"**\1\2**",
        text
    )

    # ------------------------------------------------------------
    # 4. Bold + Italic
    # ------------------------------------------------------------
    text = re.sub(
        r"\*\*\*([^*\n]+)\*\*\*",
        r"<b><i>\1</i></b>",
        text
    )

    # ------------------------------------------------------------
    # 5. Bold
    # ------------------------------------------------------------
    text = re.sub(
        r"\*\*([^*\n]+)\*\*",
        r"<b>\1</b>",
        text
    )

    # ------------------------------------------------------------
    # 6. Italic
    # ------------------------------------------------------------
    text = re.sub(
        r"(?<!\*)\*([^*\n]+)\*(?!\*)",
        r"<i>\1</i>",
        text
    )

    # ------------------------------------------------------------
    # 7. Restore inline code
    # ------------------------------------------------------------
    for key, value in placeholders.items():
        text = text.replace(key, value)

    # ------------------------------------------------------------
    # 8. Defensive cleanup
    # ------------------------------------------------------------
    # AI-generated Markdown can occasionally contain malformed
    # combinations of formatting markers. Make sure we never
    # return raw Markdown stars that could interact badly with
    # ReportLab XML parsing.
    text = text.replace("**", "")
    
    return text


def is_markdown_table_separator(line: str) -> bool:
    """
    Detect Markdown table separator:
    | --- | --- |
    """

    stripped = line.strip()

    if "|" not in stripped:
        return False

    cells = [
        cell.strip()
        for cell in stripped.strip("|").split("|")
    ]

    if not cells:
        return False

    return all(
        re.fullmatch(
            r":?-{3,}:?",
            cell
        )
        for cell in cells
    )


def split_markdown_table_row(line: str):
    """
    Convert a Markdown table row into cells.
    """

    stripped = line.strip()

    if stripped.startswith("|"):
        stripped = stripped[1:]

    if stripped.endswith("|"):
        stripped = stripped[:-1]

    return [
        cell.strip()
        for cell in stripped.split("|")
    ]


def build_reportlab_table(
    table_lines,
    styles
):
    """
    Convert Markdown table lines into ReportLab Table.
    """

    rows = []

    for line in table_lines:

        if is_markdown_table_separator(line):
            continue

        cells = split_markdown_table_row(line)

        row = []

        for cell in cells:

            cell_text = (
                markdown_inline_to_reportlab(
                    cell
                )
            )

            row.append(
                Paragraph(
                    cell_text,
                    styles["TableCell"]
                )
            )

        rows.append(row)

    if not rows:
        return None

    max_columns = max(
        len(row)
        for row in rows
    )

    normalized_rows = []

    for row in rows:

        while len(row) < max_columns:

            row.append(
                Paragraph(
                    "",
                    styles["TableCell"]
                )
            )

        normalized_rows.append(row)

    available_width = (
        A4[0] - 3 * cm
    )

    table = Table(
        normalized_rows,
        colWidths=[
            available_width / max_columns
        ] * max_columns,
        repeatRows=1,
        hAlign="LEFT"
    )

    table.setStyle(
        TableStyle(
            [
                (
                    "BACKGROUND",
                    (0, 0),
                    (-1, 0),
                    colors.HexColor("#E9EEF5")
                ),
                (
                    "TEXTCOLOR",
                    (0, 0),
                    (-1, 0),
                    colors.HexColor("#1F2937")
                ),
                (
                    "FONTNAME",
                    (0, 0),
                    (-1, 0),
                    "Helvetica-Bold"
                ),
                (
                    "GRID",
                    (0, 0),
                    (-1, -1),
                    0.4,
                    colors.HexColor("#B8C0CC")
                ),
                (
                    "VALIGN",
                    (0, 0),
                    (-1, -1),
                    "TOP"
                ),
                (
                    "LEFTPADDING",
                    (0, 0),
                    (-1, -1),
                    5
                ),
                (
                    "RIGHTPADDING",
                    (0, 0),
                    (-1, -1),
                    5
                ),
                (
                    "TOPPADDING",
                    (0, 0),
                    (-1, -1),
                    5
                ),
                (
                    "BOTTOMPADDING",
                    (0, 0),
                    (-1, -1),
                    5
                ),
            ]
        )
    )

    return table


