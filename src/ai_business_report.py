# ============================================================
# MARKDOWN → REPORTLAB PDF
# ============================================================

def markdown_to_pdf(
    markdown_text: str,
    output_pdf: Path
):
    """
    Convert integrated Markdown report into
    a professional PDF using ReportLab.

    Supports:
        # headings
        ## headings
        ### headings
        **bold**
        *italic*
        `inline code`
        bullet lists
        numbered lists
        horizontal rules
        Markdown images
        Markdown tables
        normal paragraphs
    """

    styles = getSampleStyleSheet()

    # --------------------------------------------------------
    # Custom styles
    # --------------------------------------------------------

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        alignment=TA_CENTER,
        spaceBefore=8,
        spaceAfter=18
    )

    h1_style = ParagraphStyle(
        "H1Custom",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=17,
        leading=21,
        spaceBefore=18,
        spaceAfter=10,
        keepWithNext=True
    )

    h2_style = ParagraphStyle(
        "H2Custom",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        spaceBefore=14,
        spaceAfter=8,
        keepWithNext=True
    )

    h3_style = ParagraphStyle(
        "H3Custom",
        parent=styles["Heading3"],
        fontName="Helvetica-Bold",
        fontSize=11.5,
        leading=15,
        spaceBefore=10,
        spaceAfter=7,
        keepWithNext=True
    )

    body_style = ParagraphStyle(
        "BodyCustom",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=9.5,
        leading=14,
        alignment=TA_LEFT,
        spaceAfter=8
    )

    bullet_style = ParagraphStyle(
        "BulletCustom",
        parent=body_style,
        leftIndent=15,
        firstLineIndent=-8,
        spaceAfter=4
    )

    numbered_style = ParagraphStyle(
        "NumberedCustom",
        parent=body_style,
        leftIndent=18,
        firstLineIndent=-10,
        spaceAfter=4
    )

    table_cell_style = ParagraphStyle(
        "TableCell",
        parent=body_style,
        fontSize=8,
        leading=10,
        spaceAfter=0
    )

    styles.add(
        table_cell_style
    )

    document = SimpleDocTemplate(
        str(output_pdf),
        pagesize=A4,
        rightMargin=1.5 * cm,
        leftMargin=1.5 * cm,
        topMargin=1.5 * cm,
        bottomMargin=1.5 * cm + 0.4 * cm,
        title="AI Business Intelligence Report",
        author="AI Business Analytics Pipeline"
    )

    story = []

    lines = markdown_text.splitlines()

    paragraph_buffer = []

    # --------------------------------------------------------
    # Flush paragraph
    # --------------------------------------------------------

    def flush_paragraph():

        if not paragraph_buffer:
            return

        text = " ".join(
            line.strip()
            for line in paragraph_buffer
        ).strip()

        if text:

            converted = (
                markdown_inline_to_reportlab(
                    text
                )
            )

            story.append(
                Paragraph(
                    converted,
                    body_style
                )
            )

        paragraph_buffer.clear()

    # --------------------------------------------------------
    # Process lines
    # --------------------------------------------------------

    index = 0

    while index < len(lines):

        line = lines[index]

        stripped = line.strip()

        # ----------------------------------------------------
        # Empty line
        # ----------------------------------------------------

        if not stripped:

            flush_paragraph()

            index += 1

            continue

        # ----------------------------------------------------
        # Markdown table
        # ----------------------------------------------------

        if (
            "|" in stripped
            and index + 1 < len(lines)
            and is_markdown_table_separator(
                lines[index + 1]
            )
        ):

            flush_paragraph()

            table_lines = [
                stripped
            ]

            index += 1

            while index < len(lines):

                current = lines[index].strip()

                if (
                    not current
                    or "|" not in current
                ):
                    break

                table_lines.append(
                    current
                )

                index += 1

            table = build_reportlab_table(
                table_lines,
                styles
            )

            if table:

                story.append(
                    Spacer(
                        1,
                        0.12 * cm
                    )
                )

                story.append(
                    table
                )

                story.append(
                    Spacer(
                        1,
                        0.25 * cm
                    )
                )

            continue

        # ----------------------------------------------------
        # Markdown image
        # ----------------------------------------------------

        image_match = re.match(
            r"!\[[^\]]*\]\(([^)]+)\)",
            stripped
        )

        if image_match:

            flush_paragraph()

            image_relative_path = (
                image_match.group(1)
            )

            image_path = (
                OUTPUT_DIR
                / image_relative_path
            )

            if image_path.exists():

                image = Image(
                    str(image_path)
                )

                max_width = (
                    A4[0] - 3 * cm
                )

                max_height = (
                    10 * cm
                )

                if image.imageWidth > 0:
                    width_scale = (
                        max_width
                        / image.imageWidth
                    )
                else:
                    width_scale = 1

                if image.imageHeight > 0:
                    height_scale = (
                        max_height
                        / image.imageHeight
                    )
                else:
                    height_scale = 1

                scale = min(
                    width_scale,
                    height_scale,
                    1.0
                )

                image.drawWidth = (
                    image.imageWidth * scale
                )

                image.drawHeight = (
                    image.imageHeight * scale
                )

                story.append(
                    Spacer(
                        1,
                        0.2 * cm
                    )
                )

                story.append(
                    image
                )

                story.append(
                    Spacer(
                        1,
                        0.3 * cm
                    )
                )

            else:

                print(
                    f"⚠ PDF image not found: "
                    f"{image_path}"
                )

            index += 1

            continue

        # ----------------------------------------------------
        # H1
        # ----------------------------------------------------

        if stripped.startswith("# "):

            flush_paragraph()

            text = stripped[2:].strip()

            converted = (
                markdown_inline_to_reportlab(
                    text
                )
            )

            story.append(
                Paragraph(
                    converted,
                    h1_style
                )
            )

            index += 1

            continue

        # ----------------------------------------------------
        # H2
        # ----------------------------------------------------

        if stripped.startswith("## "):

            flush_paragraph()

            text = stripped[3:].strip()

            converted = (
                markdown_inline_to_reportlab(
                    text
                )
            )

            story.append(
                Paragraph(
                    converted,
                    h2_style
                )
            )

            index += 1

            continue

        # ----------------------------------------------------
        # H3
        # ----------------------------------------------------

        if stripped.startswith("### "):

            flush_paragraph()

            text = stripped[4:].strip()

            converted = (
                markdown_inline_to_reportlab(
                    text
                )
            )

            story.append(
                Paragraph(
                    converted,
                    h3_style
                )
            )

            index += 1

            continue

        # ----------------------------------------------------
        # Horizontal rule
        # ----------------------------------------------------

        if stripped in (
            "---",
            "***",
            "___"
        ):

            flush_paragraph()

            story.append(
                Spacer(
                    1,
                    0.15 * cm
                )
            )

            index += 1

            continue

        # ----------------------------------------------------
        # Bullet
        # ----------------------------------------------------

        if (
            stripped.startswith("* ")
            or stripped.startswith("- ")
            or stripped.startswith("• ")
        ):

            flush_paragraph()

            if stripped.startswith("• "):

                text = stripped[2:].strip()

            else:

                text = stripped[2:].strip()

            converted = (
                markdown_inline_to_reportlab(
                    text
                )
            )

            story.append(
                Paragraph(
                    f"• {converted}",
                    bullet_style
                )
            )

            index += 1

            continue

        # ----------------------------------------------------
        # Numbered list
        # ----------------------------------------------------

        numbered_match = re.match(
            r"^(\d+)\.\s+(.+)$",
            stripped
        )

        if numbered_match:

            flush_paragraph()

            number = (
                numbered_match.group(1)
            )

            text = (
                numbered_match.group(2)
            )

            converted = (
                markdown_inline_to_reportlab(
                    text
                )
            )

            story.append(
                Paragraph(
                    f"{number}. {converted}",
                    numbered_style
                )
            )

            index += 1

            continue

        # ----------------------------------------------------
        # Normal paragraph
        # ----------------------------------------------------

        paragraph_buffer.append(
            stripped
        )

        index += 1

    # --------------------------------------------------------
    # Flush final paragraph
    # --------------------------------------------------------

    flush_paragraph()

    # --------------------------------------------------------
    # Build PDF
    # --------------------------------------------------------

    document.build(
        story,
        onFirstPage=draw_page_header_footer,
        onLaterPages=draw_page_header_footer
    )


