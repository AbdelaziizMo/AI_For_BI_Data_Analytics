# ============================================================
# REMOVE H1 SECTION
# ============================================================

def remove_h1_section(
    report: str,
    section_name: str
) -> str:
    """
    Remove a complete H1 Markdown section,
    including its content, until the next H1.
    """

    section_pattern = (
        rf"(?ms)^#\s+"
        rf"{re.escape(section_name)}"
        rf"\s*$.*?"
        rf"(?=^#\s+|\Z)"
    )

    return re.sub(
        section_pattern,
        "",
        report
    )


# ============================================================
# REMOVE OLD VISUALIZATION BLOCKS
# ============================================================

def remove_existing_visualization_blocks(
    report: str
) -> str:
    """
    Remove old visualization blocks and legacy
    volume-based analysis sections.

    The current sanitized dataset is revenue-focused,
    therefore legacy transaction-volume sections must
    not remain in the final report.
    """

    # --------------------------------------------------------
    # Remove Markdown image blocks
    # --------------------------------------------------------

    report = re.sub(
        r"(?m)^!\[[^\]]*\]\(visualizations/[^)]*\)\s*\n?",
        "",
        report,
        flags=re.IGNORECASE
    )

    # --------------------------------------------------------
    # Remove old visualization headings
    # --------------------------------------------------------

    visualization_titles = [
        "Daily Revenue Trend by Service",
        "Top Services by Total Revenue",
        "Total Revenue by Service",
        "Daily Revenue Intensity Heatmap by Service",
        "Total Transaction Volume by Service",
        "Total Revenue vs. Transaction Volume",
        "Total Revenue vs Transaction Volume"
    ]

    for title in visualization_titles:

        pattern = (
            r"(?m)^###\s+"
            + re.escape(title)
            + r"\s*\n?"
        )

        report = re.sub(
            pattern,
            "",
            report,
            flags=re.IGNORECASE
        )

    # --------------------------------------------------------
    # Remove legacy Revenue vs Volume H1 section
    # --------------------------------------------------------

    report = remove_h1_section(
        report,
        "Revenue vs Volume"
    )

    # --------------------------------------------------------
    # Remove legacy volume-related paragraphs
    # --------------------------------------------------------

    volume_patterns = [

        r"(?is)"
        r"•?\s*Volume Metrics Status:.*?"
        r"(?=\n\s*(?:•|[-*]|\d+\.|$))",

        r"(?is)"
        r"•?\s*Rank Comparisons:.*?"
        r"(?=\n\s*(?:•|[-*]|\d+\.|$))",

        r"(?is)"
        r"•?\s*Analytical Boundary:.*?"
        r"(?=\n\s*(?:•|[-*]|\d+\.|$))",
    ]

    for pattern in volume_patterns:

        report = re.sub(
            pattern,
            "",
            report
        )

    # --------------------------------------------------------
    # Remove legacy limitation specifically about volume
    # --------------------------------------------------------

    report = re.sub(
        r"(?is)"
        r"\d+\.\s*Absence of Transaction Volume Data:"
        r".*?"
        r"(?=\n\s*\d+\.\s|\Z)",
        "",
        report
    )

    # --------------------------------------------------------
    # Cleanup
    # --------------------------------------------------------

    report = re.sub(
        r"\n{4,}",
        "\n\n\n",
        report
    )

    return report


