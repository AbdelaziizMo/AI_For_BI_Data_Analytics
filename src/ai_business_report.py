# ============================================================
# SECTION DETECTION
# ============================================================

def get_section_for_visualization(
    title: str
):

    title_lower = title.lower().strip()

    if (
        "daily revenue trend by service"
        in title_lower
    ):

        return "Time Trend Analysis"

    if (
        "top services by total revenue"
        in title_lower
        or
        "total revenue by service"
        in title_lower
        or
        "total transaction volume by service"
        in title_lower
        or
        "heatmap"
        in title_lower
    ):

        return "Service Performance"

    if (
        "total revenue vs"
        in title_lower
    ):

        return "Revenue vs Volume"

    return None


# ============================================================
# FIND H1 SECTION
# ============================================================

def find_h1_section(
    report: str,
    section_name: str
):

    section_pattern = (
        rf"(?m)^#\s+"
        rf"{re.escape(section_name)}"
        rf"\s*$"
    )

    match = re.search(
        section_pattern,
        report
    )

    if not match:
        return None

    section_start = match.end()

    next_section_match = re.search(
        r"(?m)^#\s+",
        report[section_start:]
    )

    if next_section_match:

        section_end = (
            section_start
            + next_section_match.start()
        )

    else:

        section_end = len(report)

    return (
        section_start,
        section_end
    )


# ============================================================
# INSERT VISUALIZATIONS
# ============================================================

def insert_visualizations_into_section(
    report: str,
    section_name: str,
    charts
):

    section_info = find_h1_section(
        report,
        section_name
    )

    if not section_info:

        print(
            f"  ⚠ Section not found: "
            f"{section_name}"
        )

        return report, 0

    section_start, section_end = (
        section_info
    )

    section_content = report[
        section_start:section_end
    ]

    inserted_count = 0

    for title, chart_markdown in charts:

        if chart_markdown.strip() in section_content:
            continue

        section_content = (
            section_content.rstrip()
            + "\n\n"
            + chart_markdown.strip()
            + "\n"
        )

        inserted_count += 1

    report = (
        report[:section_start]
        + "\n"
        + section_content.lstrip()
        + "\n"
        + report[section_end:]
    )

    return (
        report,
        inserted_count
    )


# ============================================================
# INTEGRATE VISUALIZATIONS
# ============================================================

def integrate_visualizations(
    report: str,
    plan: dict
):

    visualizations = plan.get(
        "visualizations",
        []
    )

    if not visualizations:

        raise ValueError(
            "No visualizations found in plan."
        )

    section_insertions = {}

    for index, visualization in enumerate(
        visualizations,
        start=1
    ):

        title = normalize_title(
            visualization.get(
                "title",
                f"Visualization {index}"
            )
        )

        section = (
            get_section_for_visualization(
                title
            )
        )

        if not section:

            print(
                f"  ⚠ No matching section "
                f"found for: {title}"
            )

            continue

        chart_markdown = (
            build_visualization_markdown(
                visualization,
                index
            )
        )

        section_insertions.setdefault(
            section,
            []
        ).append(
            (
                title,
                chart_markdown
            )
        )

    total_inserted = 0

    for section, charts in (
        section_insertions.items()
    ):

        print(
            f"\n  Processing section: "
            f"{section}"
        )

        report, inserted_count = (
            insert_visualizations_into_section(
                report,
                section,
                charts
            )
        )

        total_inserted += inserted_count

        for title, _ in charts:

            print(
                f"    ✓ {title}"
            )

    return (
        report,
        total_inserted
    )


