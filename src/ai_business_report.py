# MARKDOWN CLEANUP
# ============================================================

def clean_markdown_formatting(report: str) -> str:
    """
    Normalize escaped Markdown characters
    generated by the AI report.
    """

    report = re.sub(
        r"(?m)^\\\*",
        "*",
        report
    )

    report = re.sub(
        r"(?m)^([0-9]+)\\\.",
        r"\1.",
        report
    )

    report = re.sub(
        r"(?m)^\\---$",
        "---",
        report
    )

    report = report.replace(
        r"\(",
        "("
    )

    report = report.replace(
        r"\)",
        ")"
    )

    report = report.replace(
        r"\_",
        "_"
    )

    report = report.replace(
        r"\*\*",
        "**"
    )

    report = report.replace(
        r"\`",
        "`"
    )

    report = re.sub(
        r"(?m)^\\\s+",
        "",
        report
    )

    report = re.sub(
        r"\n{4,}",
        "\n\n\n",
        report
    )

    return report


